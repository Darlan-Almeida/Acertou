import { test, expect } from '@playwright/test'

test('professor creates a quiz and student enters a live room', async ({ page, browser }) => {
  test.setTimeout(60000)
  const email = `teacher-${Date.now()}-${Math.random().toString(36).slice(2)}@example.com`
  await page.goto('/cadastro')
  await page.getByLabel('Seu nome').fill('Professora Ana')
  await page.getByLabel('E-mail').fill(email)
  await page.getByLabel('Senha').fill('secure-pass-123')
  await page.getByRole('button', { name: 'Criar conta' }).click()
  await expect(page.getByText('Vamos aprender juntos.')).toBeVisible()
  await page.getByRole('link', { name: 'Criar quiz' }).first().click()
  await page.getByLabel('Título do quiz').fill('Ciências ao vivo')
  await page.getByPlaceholder('Escreva sua pergunta').fill('Quanto é 2 + 2?')
  for (const [index, value] of ['3', '4', '5', '6'].entries()) await page.getByPlaceholder(`Alternativa ${index+1}`).fill(value)
  await page.getByLabel('Resposta correta 2').check()
  await page.getByLabel('Tempo (segundos)').fill('5')
  await page.getByRole('button', { name: 'Salvar quiz' }).click()
  await page.getByRole('link', { name: 'Iniciar sessão' }).click()
  await page.getByRole('button', { name: 'Criar sala' }).click()
  const code = await page.locator('.room-code').textContent()
  expect(code).toMatch(/^\d{6}$/)
  const student = await browser.newPage()
  await student.goto(`/entrar/${code}`)
  await student.getByLabel('Seu nome').fill('João')
  await student.getByRole('button', { name: 'Entrar na sala' }).click()
  await expect(student.getByText('Agora é só aguardar.')).toBeVisible()
  await expect(page.getByText('João')).toBeVisible()
  await page.getByRole('button', { name: 'Iniciar quiz' }).click()
  await expect(student.getByText('Quanto é 2 + 2?')).toBeVisible({ timeout: 10000 })
  await expect(student.getByText(/As alternativas aparecem em/)).toBeVisible()
  await expect(student.getByRole('button', { name: 'B 4' })).toHaveCount(0)
  await expect(student.getByRole('button', { name: 'B 4' })).toBeVisible({ timeout: 15000 })
  await student.getByRole('button', { name: 'B 4' }).click()
  await expect(student.getByText('Resposta registrada. O resultado aparece ao fim do tempo.')).toBeVisible()
  await expect(student.getByText(/Resposta correta!/)).toHaveCount(0)
  await expect(student.getByText(/Resposta correta!/)).toBeVisible({ timeout: 10000 })
  await page.getByRole('button', { name: 'Concluir quiz' }).click()
  await expect(student.getByText('Quiz concluído!')).toBeVisible()
  await expect(page.getByText('O pódio da turma')).toBeVisible()
  await expect(page.getByText('João')).toBeVisible()
  await page.getByRole('link', { name: 'Ver resultados' }).click()
  await expect(page.getByText('Desempenho por aluno')).toBeVisible()
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await student.close()
})
